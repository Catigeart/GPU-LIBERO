"""Deterministic CUDA derivation of frozen MuJoCo 2.3.7 and libccd bodies.
Arithmetic bodies retain source order except documented geometric corrections.
Adaptations include device qualifiers, private two-geom views and explicit guards.
"""
from libero.gpu.host.paths import GPU_ROOT, REPO_ROOT
from pathlib import Path
import argparse,hashlib,json,re,difflib

ROOT=(REPO_ROOT / '.')
MODULE=(GPU_ROOT / 'host/runtime/collision')
ORIGINALS=(GPU_ROOT / 'host/runtime/collision/native_originals')

def source(name):
    b=(ORIGINALS/(name+'.txt')).read_bytes()
    binding=json.loads(((REPO_ROOT / 'doc/phase_06/tasks/C/NATIVE_ORIGINAL_SOURCES.json')).read_text())[name]
    if hashlib.sha256(b).hexdigest()!=binding['sha256'] or len(b)!=binding['bytes']:
        raise ValueError('native original source mismatch: '+name)
    return b.decode()

def function(s,name):
    masked=re.sub(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"',
                  lambda m:' '*len(m.group()),s,flags=re.S)
    match=re.search(r'(?m)^(?:static )?(?:_ccd_inline )?(?:void|int|mjtNum|ccd_real_t)\s+'+re.escape(name)+r'\s*\(',masked)
    if not match:raise ValueError('missing function '+name)
    start=match.start();brace=masked.index('{',match.end());depth=1;i=brace+1
    while depth:
        if masked[i]=='{':depth+=1
        if masked[i]=='}':depth-=1
        i+=1
    return s[start:i]

def qualify(s):
    s=re.sub(r'(?m)^(static )?(void|int|mjtNum|ccd_real_t)(\s+\w+\s*\()',
             lambda m:(m[1] or '')+'__device__ '+m[2]+m[3],s)
    return s.replace('_ccd_inline','static __device__ __forceinline__')

def strip_includes(s):
    return re.sub(r'(?m)^#include.*\n','',s)

def correct_boxbox_edge_contacts(body):
    """Keep lateral feature gaps out of signed penetration depths.

    The no-intersection fallback clamps corners to the other face. A clamped
    point outside that face has a lateral gap, even when it is below the
    reference plane. Its Euclidean distance is positive and must fit margin.
    Keep the projection determinant intact across all four corner queries.
    """
    replacements = [
        ('      if (nl == 0) {',
         '      const int outside = u < 0 || u > 1 || v < 0 || v > 1;\n'
         '      if (nl == 0) {'),
        ('      c1 = mju_dot3(tmp2, tmp2);\n'
         '      if (tmp1[2] > 0)\n'
         '        if (c1 > margin2)',
         '      // c1 remains the projection determinant for the next corner.\n'
         '      c2 = mju_dot3(tmp2, tmp2);\n'
         '      if (outside || tmp1[2] > 0)\n'
         '        if (c2 > margin2)'),
        ('      depth[n] = sqrt(c1) * (tmp1[2] < 0 ? -1 : 1);',
         '      depth[n] = sqrt(c2) * (!outside && tmp1[2] < 0 ? -1 : 1);'),
        ('      x = ppts2[i][0];\n      y = ppts2[i][1];',
         '      x = ppts2[i][0];\n      y = ppts2[i][1];\n'
         '      const int outside = x < -lx || x > lx || y < -ly || y > ly;'),
        ('      if (pu[i][2] > 0)\n        if (c1 > margin2)',
         '      if (outside || pu[i][2] > 0)\n        if (c1 > margin2)'),
        ('      depth[n] = sqrt(c1) * (pu[i][2] < 0 ? -1 : 1);',
         '      depth[n] = sqrt(c1) * (!outside && pu[i][2] < 0 ? -1 : 1);'),
    ]
    # Restrict the first replacement to the corner-projection loop; a second
    # no-intersection branch below has a different projected-footprint test.
    head, tail = body.split('edgeedge:', 1)
    for old, new in replacements:
        if old not in tail:
            raise ValueError('BoxBox edge-contact source drift: ' + old)
        tail = tail.replace(old, new, 1)
    return head + 'edgeedge:' + tail

def derive():
    pre=r'''// Generated by scripts/gpu_phase06_collision/derive_native.py.
// Sources and notices: libero/libero/gpu/THIRD_PARTY_NOTICES.md.
// Upstream MuJoCo/libccd notices and frozen original files are retained.
#pragma once
#include <cuda_runtime.h>
#include <math.h>
#include <float.h>
#include <string.h>
#include <stddef.h>
#define mjMINVAL 1e-15
#define mjMAXCONPAIR 50
#define mju_abs fabs
#define mju_sqrt sqrt
#define mju_sin sin
#define mju_cos cos
#define mjGEOM_SPHERE 2
#define mjGEOM_CAPSULE 3
#define mjGEOM_ELLIPSOID 4
#define mjGEOM_CYLINDER 5
#define mjGEOM_BOX 6
#define mjGEOM_MESH 7
#define mjENBL_MULTICCD 1
#define mjENABLED(flag) (m->opt.enableflags & (flag))
#define mju_min(a,b) ((a)<(b)?(a):(b))
typedef double mjtNum;
struct NativeOption { int mpr_iterations,enableflags; double mpr_tolerance; };
struct mjModel {
 double* geom_size; double* geom_rbound; int* geom_type; int* geom_dataid;
 float* mesh_vert; int* mesh_vertadr; int* mesh_vertnum; int* mesh_graphadr; int* mesh_graph;
 NativeOption opt; int* adapter_error; int* adapter_diag; int* adapter_frame0;
 int nvert,ngraph,nmesh,watchdog;
};
struct mjData { double* geom_xpos; double* geom_xmat; };
struct mjContact { double dist,pos[3],frame[9]; };
struct mjtCCD { const mjModel* model; const mjData* data; int geom,meshindex; double margin,rotate[4]; };
'''
    parts=[pre];diffs=[]
    groups=[
    ('engine_util_blas.c',['mju_zero3','mju_copy3','mju_scl3','mju_add3','mju_sub3','mju_addTo3','mju_subFrom3','mju_addToScl3','mju_addScl3','mju_normalize3','mju_norm3','mju_dot3','mju_dist3','mju_rotVecMat','mju_rotVecMatT','mju_zero','mju_copy','mju_addToScl','mju_dot','mju_norm','mju_transpose','mju_mulMatMat','mju_mulMatMatT','mju_mulMatTMat']),
    ('engine_util_spatial.c',['mju_axisAngle2Quat','mju_quat2Mat','mju_cross','mju_makeFrame']),
    ('engine_util_misc.c',['mju_sign']),
    ]
    functions=[]
    for name,names in groups:
        s=source(name)
        for fn in names:
            old=function(s,fn);new=qualify(old)
            if fn=='mju_makeFrame':
                new=new.replace('mjERROR("xaxis of contact frame undefined");','frame[0] = nan(""); return; // invalid normal propagated by finite check')
            functions.append((name,fn,old,new))
    for name,fn,old,new in functions:
        parts.append(new[:new.index('{')].strip()+';')
    for name,fn,old,new in functions:
        parts.append('\n// Original '+name+' :: '+fn+'\n'+new)
        diffs.append(''.join(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile=name+'::'+fn,tofile='device::'+fn)))
    parts.append('#define CCD_DOUBLE\n#define CCD_EXPORT __device__\n')
    for n in ['ccd_vec3.h','ccd_ccd.h','ccd_support.h','ccd_simplex.h']:
        old=source(n);new=qualify(strip_includes(old))
        if n=='ccd_ccd.h':
            new=new.replace('struct _ccd_t {','struct _ccd_t {\n    int *adapter_error, *adapter_diag; int watchdog;')
        parts.append(new)
        diffs.append(''.join(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile=n,tofile='device::'+n)))
    parts.append(r'''
__device__ ccd_vec3_t native_origin = {{0.0,0.0,0.0}};
extern "C" { __device__ ccd_vec3_t* ccd_vec3_origin = &native_origin; }
__device__ int native_mpr_guard(const ccd_t* ccd,int phase) {
 if (++ccd->adapter_diag[phase] > ccd->watchdog) { *ccd->adapter_error=6; return 0; }
 return 1;
}
''')
    vec=source('ccd_vec3.c')
    old=vec[vec.index('_ccd_inline ccd_real_t'):]
    new=qualify(old)
    parts.append(new)
    diffs.append(''.join(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile='ccd_vec3.c::distance',tofile='device::distance')))
    old=function(source('ccd.c'),'ccdFirstDirDefault');parts.append(qualify(old))
    old=source('ccd_support.c');new=qualify(strip_includes(old))
    new=new.replace('ccd_vec3_t dir;','ccd_vec3_t dir;\n    ++ccd->adapter_diag[3];')
    parts.append(new)
    diffs.append(''.join(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile='ccd_support.c',tofile='device::support')))
    old=source('ccd_mpr.c');new=qualify(strip_includes(old))
    new=new.replace('while (ccdSimplexSize(portal) < 4){','while (ccdSimplexSize(portal) < 4){\n        if (!native_mpr_guard(ccd,0)) return -2;')
    new=new.replace('while (1){','while (1){\n        if (!native_mpr_guard(ccd,1)) return -2;',1)
    match=list(re.finditer(r'static __device__ void findPenetr\([^;]*?\)\s*\{',new,re.S))[-1]
    before=new[:match.start()];after=new[match.start():]
    after=after.replace('while (1){','while (1){\n        if (!native_mpr_guard(ccd,2)) return;',1)
    new=before+after
    parts.append(new)
    diffs.append(''.join(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile='ccd_mpr.c',tofile='device::mpr')))
    convex=source('engine_collision_convex.c')
    names=['mjccd_center','mjccd_support','mjc_ellipsoidInside','mjc_ellipsoidOutside','mjc_fixNormal','mjc_MPRIteration','mjc_isDistinctContact','mju_rotateFrame','mjc_Convex']
    originals=[]
    for name in names:
        old=function(convex,name);new=qualify(old)
        if name=='mjccd_support':
            new=new.replace('while (change) {','int adapter_steps=0;\n      while (change) {\n        if (++adapter_steps > m->watchdog) { *m->adapter_error=6; mju_zero3(vec->v); return; }')
            new=new.replace('mju_warning("mesh_support could not find support vertex");','*m->adapter_error=7;')
            new=new.replace('mjERROR("ccd support function is undefined for geom type %d", m->geom_type[g]);','*m->adapter_error=4; mju_zero3(res);')
        if name=='mjc_Convex':
            new=new.replace('ccd_t ccd;','ccd_t ccd;\n  ccd.adapter_error=m->adapter_error; ccd.adapter_diag=m->adapter_diag; ccd.watchdog=m->watchdog;')
        originals.append((name,old,new))
    for name,old,new in originals:parts.append(new[:new.index('{')].strip()+';')
    for name,old,new in originals:
        parts.append(new)
        diffs.append(''.join(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile='engine_collision_convex.c::'+name,tofile='device::'+name)))
    old=function(source('engine_collision_box.c'),'mjc_BoxBox');new=qualify(correct_boxbox_edge_contacts(old))
    new=new.replace('if (code == -1)', 'M->adapter_diag[6]=code;\n  if (code == -1)')
    new=new.replace('mju_copy3(con[0].frame, tmp2);','*M->adapter_frame0=1;\n  mju_copy3(con[0].frame, tmp2);')
    new=new.replace('mju_scl3(con[0].frame, tmp1, in ? -1 : 1);','*M->adapter_frame0=1;\n  mju_scl3(con[0].frame, tmp1, in ? -1 : 1);')
    parts.append(new)
    diffs.append(''.join(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile='engine_collision_box.c::mjc_BoxBox',tofile='device::mjc_BoxBox')))
    return '\n'.join(parts)+'\n','\n'.join(diffs)

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    header,diff=derive()
    targets={(GPU_ROOT / 'cuda/collision/native/native_source.cuh'):header,(REPO_ROOT / 'doc/phase_06/tasks/C/NATIVE_GENERATION.diff'):diff}
    for path,value in targets.items():
        if args.check:
            if path.read_text()!=value:raise ValueError('generated source drift: '+str(path))
        else:path.write_text(value)
    print('native derivation verified' if args.check else 'native derivation generated')
if __name__=='__main__':main()
